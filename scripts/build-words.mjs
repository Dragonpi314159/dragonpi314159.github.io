// Builds data/words.js (the word lists the game ships with).
//
//   node scripts/build-words.mjs            -> starter list only (works offline)
//   npm i -D oxford_3000 an-array-of-english-words leo-profanity obscenity
//   node scripts/build-words.mjs --full     -> bigger list, see below
//
// SAFETY MODEL (no slurs are written anywhere in this repo):
//  * Word lists come from learner/school vocabulary (starter file + Oxford 3000).
//  * In --full mode a large dictionary is only used to CHECK SPELLING. A word is
//    kept only if it is a school-list word or a plain inflection of one
//    (plural, -ed, -ing, -er, -est, -ly). Anything else is dropped, so rare or
//    offensive words never get in by construction.
//  * As a second net, leo-profanity / obscenity (third-party packages, run at build
//    time only) are used to drop anything they flag. Their data never ships.
//  * Skim data/words.js once before going live; her in-dashboard ban list is the last guard.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const full = process.argv.includes('--full');

const tryReq = (n) => { try { return require(n); } catch { return null; } };
const starter = fs.readFileSync(new URL('../data/starter-words.txt', import.meta.url), 'utf8')
  .split(/\s+/).map(w => w.toLowerCase()).filter(w => /^[a-z]{2,12}$/.test(w));

const roots = new Set(starter);
let big = null;
const flaggers = [];

if (full) {
  const ox = tryReq('oxford_3000');
  if (!ox) throw new Error('Run: npm i -D oxford_3000 an-array-of-english-words leo-profanity obscenity');
  ox.map(w => String(w).toLowerCase()).filter(w => /^[a-z]{2,12}$/.test(w)).forEach(w => roots.add(w));
  const bigArr = tryReq('an-array-of-english-words');
  if (bigArr) big = new Set(bigArr);
  const leo = tryReq('leo-profanity');
  if (leo) flaggers.push(w => leo.check(w));
  const ob = tryReq('obscenity');
  if (ob) {
    const m = new ob.RegExpMatcher({ ...ob.englishDataset.build(), ...ob.englishRecommendedTransformers });
    flaggers.push(w => m.hasMatch(w));
  }
  if (!flaggers.length) console.warn('WARNING: no profanity filter package found; relying on school-list allowlist only.');
}

export function inflections(root) {
  const out = new Set([root]);
  const last = root.at(-1), pen = root.at(-2);
  const vowel = 'aeiou';
  out.add(root + 's');
  if (/(s|x|z|ch|sh)$/.test(root)) out.add(root + 'es');
  if (last === 'y' && !vowel.includes(pen)) { out.add(root.slice(0, -1) + 'ies'); out.add(root.slice(0, -1) + 'ied'); out.add(root.slice(0, -1) + 'ier'); out.add(root.slice(0, -1) + 'iest'); out.add(root.slice(0, -1) + 'ily'); }
  if (last === 'e') { out.add(root + 'd'); out.add(root.slice(0, -1) + 'ing'); out.add(root + 'r'); out.add(root + 'st'); }
  else { out.add(root + 'ed'); out.add(root + 'ing'); out.add(root + 'er'); out.add(root + 'est'); out.add(root + 'ly'); }
  if (/[^aeiou][aeiou][^aeiouwxy]$/.test(root) && root.length <= 5) {
    out.add(root + last + 'ed'); out.add(root + last + 'ing'); out.add(root + last + 'er');
  }
  return out;
}

let valid = new Set(starter);
if (full) {
  const cand = new Set();
  for (const r of roots) for (const w of inflections(r)) cand.add(w);
  valid = new Set([...cand].filter(w => roots.has(w) || (big && big.has(w))));
}
const clean = (w) => w.length >= 2 && w.length <= 10 && !flaggers.some(f => f(w));
valid = new Set([...valid].filter(clean));
const bases = [...valid].filter(w => roots.has(w) && w.length >= 5 && w.length <= 9);

const sorted = (s) => [...s].sort();
const out = `// GENERATED by scripts/build-words.mjs${full ? ' --full' : ' (starter)'} - do not edit by hand.\n` +
  `export const BASES = ${JSON.stringify(sorted(bases))};\nexport const VALID = ${JSON.stringify(sorted(valid))};\n`;
fs.writeFileSync(new URL('../data/words.js', import.meta.url), out);
console.log(`bases: ${bases.length}, valid words: ${valid.size}${full ? ' (full)' : ' (starter)'}`);
